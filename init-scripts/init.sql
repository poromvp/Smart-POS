-- ============================================================================
-- PHẦN 1: TẠO 3 DATABASE TÁCH BIỆT
-- ============================================================================
CREATE DATABASE pos_identity_db;
CREATE DATABASE pos_catalog_inventory_db;
CREATE DATABASE pos_sales_db;

-- ============================================================================
-- PHẦN 2: DỊCH VỤ 1 - IDENTITY SERVICE (pos_identity_db)
-- Chịu trách nhiệm: Users, Roles, Dynamic Permissions
-- ============================================================================
\c pos_identity_db;

CREATE TABLE "roles" (
                         "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         "name" varchar(50) UNIQUE NOT NULL,
                         "description" varchar(255)
);

CREATE TABLE "permissions" (
                               "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               "code" varchar(100) UNIQUE NOT NULL,
                               "name" varchar(150) NOT NULL,
                               "module" varchar(50) NOT NULL
);

CREATE TABLE "role_permissions" (
                                    "role_id" bigint NOT NULL,
                                    "permission_id" bigint NOT NULL,
                                    PRIMARY KEY ("role_id", "permission_id"),
                                    CONSTRAINT fk_rp_role FOREIGN KEY ("role_id") REFERENCES "roles" ("id") ON DELETE CASCADE,
                                    CONSTRAINT fk_rp_permission FOREIGN KEY ("permission_id") REFERENCES "permissions" ("id") ON DELETE CASCADE
);

CREATE TABLE "users" (
                         "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         "username" varchar(50) UNIQUE NOT NULL,
                         "password_hash" varchar(255) NOT NULL,
                         "full_name" varchar(100) NOT NULL,
                         "phone" varchar(20),
                         "is_active" boolean NOT NULL DEFAULT true,
                         "created_at" timestamp DEFAULT (now())
);

CREATE TABLE "user_roles" (
                              "user_id" bigint NOT NULL,
                              "role_id" bigint NOT NULL,
                              PRIMARY KEY ("user_id", "role_id"),
                              CONSTRAINT fk_ur_user FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE,
                              CONSTRAINT fk_ur_role FOREIGN KEY ("role_id") REFERENCES "roles" ("id") ON DELETE CASCADE
);

COMMENT ON COLUMN "roles"."name" IS 'ADMIN, CASHIER, KITCHEN_LEAD...';
COMMENT ON COLUMN "permissions"."code" IS 'ORDER_CREATE, INVENTORY_IMPORT, REPORT_VIEW...';
COMMENT ON COLUMN "permissions"."name" IS 'Tên quyền hiển thị trên UI';
COMMENT ON COLUMN "permissions"."module" IS 'ORDER, INVENTORY, KDS, REPORT, SYSTEM...';


-- ============================================================================
-- PHẦN 3: DỊCH VỤ 2 - CATALOG & INVENTORY SERVICE (pos_catalog_inventory_db)
-- Chịu trách nhiệm: Menu, Modifier, Bàn ăn, Quản lý Kho, Nhà cung cấp, Định lượng BOM
-- ============================================================================
\c pos_catalog_inventory_db;

-- 1. Khu vực & Bàn ăn
CREATE TABLE "areas" (
                         "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         "name" varchar(100) NOT NULL,
                         "description" varchar(255)
);

CREATE TABLE "dining_tables" (
                                 "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 "area_id" bigint NOT NULL,
                                 "table_number" varchar(50) NOT NULL,
                                 "capacity" int DEFAULT 4,
                                 "status" varchar(30) NOT NULL DEFAULT 'EMPTY',
                                 "qr_code_token" varchar(100) UNIQUE,
                                 CONSTRAINT fk_table_area FOREIGN KEY ("area_id") REFERENCES "areas" ("id") ON DELETE CASCADE
);

-- 2. Menu Sản phẩm & Modifiers
CREATE TABLE "categories" (
                              "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              "name" varchar(100) NOT NULL,
                              "display_order" int DEFAULT 0,
                              "is_active" boolean DEFAULT true
);

CREATE TABLE "products" (
                            "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            "category_id" bigint NOT NULL,
                            "name" varchar(150) NOT NULL,
                            "code" varchar(50) UNIQUE,
                            "base_price" decimal(12,2) NOT NULL DEFAULT 0,
                            "image_url" text,
                            "description" text,
                            "is_active" boolean DEFAULT true,
                            "created_at" timestamp DEFAULT (now()),
                            CONSTRAINT fk_product_category FOREIGN KEY ("category_id") REFERENCES "categories" ("id") ON DELETE RESTRICT
);

CREATE TABLE "product_variants" (
                                    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    "product_id" bigint NOT NULL,
                                    "size_name" varchar(50) NOT NULL,
                                    "price_adjustment" decimal(12,2) NOT NULL DEFAULT 0,
                                    "sku" varchar(50) UNIQUE,
                                    CONSTRAINT fk_variant_product FOREIGN KEY ("product_id") REFERENCES "products" ("id") ON DELETE CASCADE
);

CREATE TABLE "modifier_groups" (
                                   "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   "name" varchar(100) NOT NULL,
                                   "is_multiple" boolean DEFAULT true,
                                   "is_required" boolean DEFAULT false
);

CREATE TABLE "modifier_options" (
                                    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    "group_id" bigint NOT NULL,
                                    "name" varchar(100) NOT NULL,
                                    "price" decimal(12,2) DEFAULT 0,
                                    CONSTRAINT fk_option_group FOREIGN KEY ("group_id") REFERENCES "modifier_groups" ("id") ON DELETE CASCADE
);

CREATE TABLE "product_modifier_groups" (
                                           "product_id" bigint NOT NULL,
                                           "modifier_group_id" bigint NOT NULL,
                                           PRIMARY KEY ("product_id", "modifier_group_id"),
                                           CONSTRAINT fk_pmg_product FOREIGN KEY ("product_id") REFERENCES "products" ("id") ON DELETE CASCADE,
                                           CONSTRAINT fk_pmg_group FOREIGN KEY ("modifier_group_id") REFERENCES "modifier_groups" ("id") ON DELETE CASCADE
);

-- 3. Kho hàng, Nhà cung cấp & BOM (Công thức định lượng)
CREATE TABLE "suppliers" (
                             "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             "name" varchar(150) NOT NULL,
                             "phone" varchar(20),
                             "email" varchar(100),
                             "address" text,
                             "is_active" boolean DEFAULT true
);

CREATE TABLE "ingredients" (
                               "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               "name" varchar(100) NOT NULL,
                               "code" varchar(50) UNIQUE,
                               "unit" varchar(20) NOT NULL,
                               "current_stock" decimal(12,2) NOT NULL DEFAULT 0,
                               "min_threshold" decimal(12,2) NOT NULL DEFAULT 0,
                               "cost_per_unit" decimal(12,2) DEFAULT 0
);

CREATE TABLE "recipes" (
                           "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           "product_id" bigint,
                           "variant_id" bigint,
                           "modifier_option_id" bigint,
                           "ingredient_id" bigint NOT NULL,
                           "quantity_needed" decimal(10,3) NOT NULL,
                           CONSTRAINT fk_recipe_product FOREIGN KEY ("product_id") REFERENCES "products" ("id") ON DELETE CASCADE,
                           CONSTRAINT fk_recipe_variant FOREIGN KEY ("variant_id") REFERENCES "product_variants" ("id") ON DELETE CASCADE,
                           CONSTRAINT fk_recipe_modifier FOREIGN KEY ("modifier_option_id") REFERENCES "modifier_options" ("id") ON DELETE CASCADE,
                           CONSTRAINT fk_recipe_ingredient FOREIGN KEY ("ingredient_id") REFERENCES "ingredients" ("id") ON DELETE RESTRICT
);

CREATE TABLE "purchase_orders" (
                                   "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   "po_number" varchar(50) UNIQUE NOT NULL,
                                   "supplier_id" bigint NOT NULL,
                                   "staff_id" bigint NOT NULL, -- Logical ID từ Identity Service
                                   "order_date" date NOT NULL,
                                   "delivery_date" date,
                                   "total_amount" decimal(14,2) NOT NULL DEFAULT 0,
                                   "status" varchar(30) NOT NULL DEFAULT 'DRAFT',
                                   "note" text,
                                   "created_at" timestamp DEFAULT (now()),
                                   CONSTRAINT fk_po_supplier FOREIGN KEY ("supplier_id") REFERENCES "suppliers" ("id") ON DELETE RESTRICT
);

CREATE TABLE "purchase_order_items" (
                                        "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        "purchase_order_id" bigint NOT NULL,
                                        "ingredient_id" bigint NOT NULL,
                                        "quantity" decimal(10,3) NOT NULL,
                                        "unit_price" decimal(12,2) NOT NULL,
                                        "total_price" decimal(14,2) NOT NULL,
                                        "expiry_date" date,
                                        CONSTRAINT fk_poi_order FOREIGN KEY ("purchase_order_id") REFERENCES "purchase_orders" ("id") ON DELETE CASCADE,
                                        CONSTRAINT fk_poi_ingredient FOREIGN KEY ("ingredient_id") REFERENCES "ingredients" ("id") ON DELETE RESTRICT
);

CREATE TABLE "inventory_transactions" (
                                          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                          "ingredient_id" bigint NOT NULL,
                                          "order_item_id" bigint,         -- Logical ID từ Sales Service (khi bán trừ kho)
                                          "purchase_order_item_id" bigint, -- Khóa ngoại nội bộ khi nhập hàng
                                          "quantity" decimal(10,3) NOT NULL,
                                          "transaction_type" varchar(30) NOT NULL,
                                          "created_at" timestamp DEFAULT (now()),
                                          CONSTRAINT fk_it_ingredient FOREIGN KEY ("ingredient_id") REFERENCES "ingredients" ("id") ON DELETE RESTRICT,
                                          CONSTRAINT fk_it_poi FOREIGN KEY ("purchase_order_item_id") REFERENCES "purchase_order_items" ("id") ON DELETE SET NULL
);

COMMENT ON COLUMN "areas"."name" IS 'Tầng 1, Ngoài trời, Sân thượng...';
COMMENT ON COLUMN "dining_tables"."table_number" IS 'Bàn 01, Bàn 02...';
COMMENT ON COLUMN "dining_tables"."status" IS 'EMPTY, OCCUPIED, RESERVED';
COMMENT ON COLUMN "dining_tables"."qr_code_token" IS 'Token UUID sinh mã QR tĩnh tại bàn';
COMMENT ON COLUMN "purchase_orders"."staff_id" IS 'Logical ID tham chiếu sang pos_identity_db.users.id';
COMMENT ON COLUMN "inventory_transactions"."order_item_id" IS 'Logical ID tham chiếu sang pos_sales_db.order_items.id';


-- ============================================================================
-- PHẦN 4: DỊCH VỤ 3 - SALES SERVICE (pos_sales_db)
-- Chịu trách nhiệm: Đơn hàng POS, Điều phối KDS, Thanh toán, Loyalty & Promotions
-- ============================================================================
\c pos_sales_db;

-- 1. Khách hàng thân thiết & Khuyến mãi
CREATE TABLE "customers" (
                             "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             "phone" varchar(20) UNIQUE NOT NULL,
                             "full_name" varchar(100),
                             "current_points" int DEFAULT 0,
                             "total_spent" decimal(14,2) DEFAULT 0,
                             "created_at" timestamp DEFAULT (now())
);

CREATE TABLE "promotions" (
                              "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              "code" varchar(50) UNIQUE NOT NULL,
                              "name" varchar(150) NOT NULL,
                              "discount_percent" decimal(5,2) NOT NULL,
                              "max_discount_amount" decimal(12,2),
                              "min_order_amount" decimal(12,2) DEFAULT 0,
                              "start_date" timestamp NOT NULL,
                              "end_date" timestamp NOT NULL,
                              "usage_limit" int,
                              "used_count" int DEFAULT 0,
                              "is_active" boolean DEFAULT true
);

-- 2. Đơn hàng & KDS Bếp
CREATE TABLE "orders" (
                          "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          "order_code" varchar(50) UNIQUE NOT NULL,
                          "table_id" bigint,            -- Logical ID từ Catalog Service (bảng dining_tables)
                          "customer_id" bigint,         -- Khóa ngoại nội bộ sang customers
                          "promotion_id" bigint,        -- Khóa ngoại nội bộ sang promotions
                          "staff_id" bigint,            -- Logical ID từ Identity Service (bảng users)
                          "order_type" varchar(30) NOT NULL DEFAULT 'DINE_IN',
                          "status" varchar(30) NOT NULL DEFAULT 'PENDING_APPROVAL',
                          "subtotal" decimal(12,2) NOT NULL DEFAULT 0,
                          "discount_amount" decimal(12,2) DEFAULT 0,
                          "points_discount_amount" decimal(12,2) DEFAULT 0,
                          "total_amount" decimal(12,2) NOT NULL DEFAULT 0,
                          "created_at" timestamp DEFAULT (now()),
                          "updated_at" timestamp DEFAULT (now()),
                          CONSTRAINT fk_orders_customer FOREIGN KEY ("customer_id") REFERENCES "customers" ("id") ON DELETE SET NULL,
                          CONSTRAINT fk_orders_promotion FOREIGN KEY ("promotion_id") REFERENCES "promotions" ("id") ON DELETE SET NULL
);

CREATE TABLE "point_transactions" (
                                      "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      "customer_id" bigint NOT NULL,
                                      "order_id" bigint,
                                      "points_change" int NOT NULL,
                                      "type" varchar(20) NOT NULL,
                                      "created_at" timestamp DEFAULT (now()),
                                      CONSTRAINT fk_pt_customer FOREIGN KEY ("customer_id") REFERENCES "customers" ("id") ON DELETE CASCADE,
                                      CONSTRAINT fk_pt_order FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE SET NULL
);

CREATE TABLE "order_items" (
                               "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               "order_id" bigint NOT NULL,
                               "product_id" bigint NOT NULL, -- Logical ID từ Catalog Service (bảng products)
                               "variant_id" bigint,          -- Logical ID từ Catalog Service (bảng product_variants)
                               "quantity" int NOT NULL DEFAULT 1,
                               "unit_price" decimal(12,2) NOT NULL,
                               "total_price" decimal(12,2) NOT NULL,
                               "note" text,
                               "kds_status" varchar(30) NOT NULL DEFAULT 'PENDING',
                               "created_at" timestamp DEFAULT (now()),
                               CONSTRAINT fk_item_order FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE CASCADE
);

CREATE TABLE "order_item_modifiers" (
                                        "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                        "order_item_id" bigint NOT NULL,
                                        "modifier_option_id" bigint NOT NULL, -- Logical ID từ Catalog Service (bảng modifier_options)
                                        "extra_price" decimal(12,2) NOT NULL DEFAULT 0,
                                        CONSTRAINT fk_oim_order_item FOREIGN KEY ("order_item_id") REFERENCES "order_items" ("id") ON DELETE CASCADE
);

-- 3. Thanh toán
CREATE TABLE "payments" (
                            "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            "order_id" bigint NOT NULL,
                            "payment_method" varchar(30) NOT NULL,
                            "amount" decimal(12,2) NOT NULL,
                            "status" varchar(30) NOT NULL DEFAULT 'PENDING',
                            "transaction_ref" varchar(100),
                            "paid_at" timestamp,
                            CONSTRAINT fk_payment_order FOREIGN KEY ("order_id") REFERENCES "orders" ("id") ON DELETE CASCADE
);

-- Bổ sung Transactional Outbox Pattern cho Sales Service
CREATE TABLE "outbox_events" (
                                 "id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 "aggregate_type" varchar(50) NOT NULL,
                                 "aggregate_id" bigint NOT NULL,
                                 "event_type" varchar(100) NOT NULL,
                                 "payload" jsonb NOT NULL,
                                 "created_at" timestamp DEFAULT (now()),
                                 "processed" boolean DEFAULT false
);

COMMENT ON COLUMN "orders"."table_id" IS 'Logical ID tham chiếu sang pos_catalog_inventory_db.dining_tables.id';
COMMENT ON COLUMN "orders"."staff_id" IS 'Logical ID tham chiếu sang pos_identity_db.users.id';
COMMENT ON COLUMN "order_items"."product_id" IS 'Logical ID tham chiếu sang pos_catalog_inventory_db.products.id';
COMMENT ON COLUMN "order_items"."variant_id" IS 'Logical ID tham chiếu sang pos_catalog_inventory_db.product_variants.id';
COMMENT ON COLUMN "order_item_modifiers"."modifier_option_id" IS 'Logical ID tham chiếu sang pos_catalog_inventory_db.modifier_options.id';